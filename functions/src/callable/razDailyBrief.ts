import { onCall } from "firebase-functions/v2/https";
import * as logger from "firebase-functions/logger";
import { parseRazDailyBriefPayload } from "../contracts/types";
import { GEMINI_API_KEY, routeToProvider } from "../lib/ai/aiService";
import { buildCoachContext, buildPlayerContext } from "../lib/intelligence/razContext";
import { hashContext } from "../lib/intelligence/contextHash";
import { getCachedReasoning, setCachedReasoning } from "../lib/intelligence/razCache";
import { deriveFootballReasoning } from "../lib/intelligence/razEngine";
import { buildDailyBriefMessages, parseDailyBriefSections } from "../lib/intelligence/razConversation";
import { FootballReasoning, RazHighlight, RazResponse } from "../lib/intelligence/types";
import { requireSignedIn } from "../lib/ingestionAuth";
import { enforceRateLimit } from "../lib/rateLimit";

function highlightsFor(reasoning: FootballReasoning): RazHighlight[] {
  const highlights: RazHighlight[] = [];
  if (reasoning.performanceInsight.trainingStatus) {
    highlights.push({ label: "Status", value: reasoning.performanceInsight.trainingStatus });
  }
  if (reasoning.performanceInsight.squadByStatus) {
    const total = Object.values(reasoning.performanceInsight.squadByStatus).reduce((a, b) => a + b, 0);
    if (total > 0) highlights.push({ label: "Squad", value: String(total) });
  }
  const next = reasoning.sessionInsight.upcoming[0];
  if (next) {
    highlights.push({
      label: reasoning.audience === "player" ? "Next training" : "Sessions today",
      value:
        reasoning.audience === "player"
          ? next.scheduledAt.toLocaleString("en-US", { weekday: "short", hour: "numeric", minute: "2-digit" })
          : String(reasoning.sessionInsight.upcoming.length),
    });
  }
  if (reasoning.riskExplanation.hasElevatedRisk) {
    highlights.push({ label: "Risk", value: "Elevated" });
  }
  return highlights;
}

/**
 * RAZ's Daily Brief — the primary Vikzar experience. RazContext ->
 * RazEngine (pure, structured, cached by context hash) ->
 * RazConversation -> Model Router -> Structured Response. `highlights`
 * and `confidence` come straight from the `FootballReasoning` RazEngine
 * already derived — never re-computed here, never generated by the
 * model.
 *
 * Note on scope: the brief only ever narrates what's genuinely
 * available today (training status, next session, alerts) — no
 * persisted recovery-trend value exists in this schema yet. See
 * `RecoveryInsight`'s doc comment in `types.ts`.
 */
export const razDailyBrief = onCall({ secrets: [GEMINI_API_KEY] }, async (request) => {
  const uid = requireSignedIn(request);
  const payload = parseRazDailyBriefPayload(request.data);

  const context =
    payload.audience === "player" ? await buildPlayerContext(uid) : await buildCoachContext(uid);
  const contextHash = hashContext(context);

  const cached = await getCachedReasoning(uid, payload.audience, contextHash);
  logger.info("raz_daily_brief_cache", { audience: payload.audience, hit: cached != null });
  if (cached) return cached;

  await enforceRateLimit(uid, "razDailyBrief", { maxCalls: 10, windowSeconds: 60 });

  const reasoning = deriveFootballReasoning(context, payload.audience);
  const messages = buildDailyBriefMessages(reasoning);
  const rawText = await routeToProvider("gemini").generateText(messages);
  const sections = parseDailyBriefSections(rawText, payload.audience);

  const response: RazResponse = {
    text: sections.map((s) => s.body).join(" "),
    sections,
    highlights: highlightsFor(reasoning),
    confidence: reasoning.confidence.level,
    traceRefs: reasoning.traceRefs,
    awareness: reasoning.awareness,
  };

  await setCachedReasoning(uid, payload.audience, contextHash, response);
  return response;
});
